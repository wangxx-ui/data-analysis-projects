#第三种方法：（正则表达式）
#关于这个新的extractall这个关键字，对于我来说
#这个跟findall一样会是一个很常用的关键字


# str.extractall() 返回的是一个 DataFrame，而不是 Series。
#
# 它的索引是 MultiIndex（多层索引），第一层是原 DataFrame 的索引，
# 第二层是匹配到的结果的编号（从 0 开始）。
#
# 例如，如果原数据某一行的 '备注' 列里有 3 个电话号码，extractall() 就会为这一行生成 3 行结果，
# 并用 0, 1, 2 来标记它们。然后这种事不能直接加到新列中的


#还有现在就用新列代替旧列，是没问题的
df['销量_new'] = df['销量'].str.extract(r'(\d+)\W*\+*')
#还有种写法（不是特别完善的）
#这种写法如果销量中有小数，小数是会被截断的
#但是如果有小数的话，那还不如上面那种直接对源数据进行相乘
df['销量_new'] = df['销量'].str.extract(r'(\d+)')

#不截断小数
#?在这里这个问号的含义是出现0次或者1次
df['销量_new'] = df['销量'].str.extract(r'(\d+\.?\d*)')

















