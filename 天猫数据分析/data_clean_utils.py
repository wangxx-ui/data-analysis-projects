# 用途：处理含“万”“亿”“+”等单位的数值列，支持函数调用和正则提取（不太建议用正则提取）
# 关于上面的不太建议内容，原因如下：
#     1.正则表达式主要是做提取工作，但是我们如果是为了处理销量数据
# 是不能直接提取的，比如说10万跟10亿是两个完全不同是数据，但是用.str.extract()这个函数的话
# 就是都会提取成10 ，那么在这个情况下10万跟10亿相等是不合理的
#     2.正则表达式我个人觉得还是比较吃正则基础的，况且.str.extract这个函数也是在学习了数据分析后才
# 见到的，也就是说写正则表达式会比较陌生（如果基础不太好），这个陌生函数会结合不熟练的正则表达式
# 一起加重我们的学习负担



#第一种方法：
#写函数，然后再源代码中调用
def convert_sales(value):
    # 第1步：如果已经是数字，直接返回
    if isinstance(value, (int, float)):
        return float(value)

    # 第2步：转成字符串，去掉首尾空格
    s = str(value).strip()

    # 第3步：如果包含'万'，说明是以万为单位，需要乘10000
    if '万' in s:
        # 去掉'+'和'万'，只保留数字部分
        num_str = s.replace('万', '').replace('+', '')
        # 把字符串转成数字，再乘10000
        return float(num_str) * 10000
    else:
        # 没有'万'，只去掉'+'，直接转成数字
        return float(s.replace('+', ''))

